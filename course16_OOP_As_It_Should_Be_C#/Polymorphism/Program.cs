// C# Support two type of Polymorphism:


// 1- compile time polymorphism (Also known as method overloading ) :

// method overloading allow multiple method to have the same name but with different prameters
// the compiler  select the appropriate method  to call based on number , type, and order of prameters



// 2- Run Time Polymorphism (also known as overriding ) :

//  method overriding allow the subclass  to provide specific implementataion of a method that already provided by the parent class 
// the method in the subclass most have the same signature (name , retrun type, prameters) as the method in the parent class 




